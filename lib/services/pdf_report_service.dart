  /// Generate & Launch Expenditure Account PDF Print / Save Preview
  static Future<void> printExpenditureAccountReport({
    required PujaProvider provider,
    required ExpenditureAccount account,
    required ExpenditureAccountPdfFilter filter,
  }) async {
    final pdfBytes = await generateExpenditureAccountPdf(
      provider: provider,
      account: account,
      filter: filter,
    );
    final filterSuffix = filter == ExpenditureAccountPdfFilter.all
        ? 'All'
        : (filter == ExpenditureAccountPdfFilter.cashOnly
            ? 'Cash'
            : (filter == ExpenditureAccountPdfFilter.upiOnly ? 'UPI' : 'Bank'));
    final safeName = '${account.accountName.replaceAll(' ', '_')}_Expense_${filterSuffix}_${provider.currentYear}.pdf';
    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdfBytes,
      name: safeName,
    );
  }

  /// Generate & Share Expenditure Account PDF directly via WhatsApp / Apps
  static Future<void> shareExpenditureAccountReport({
    required PujaProvider provider,
    required ExpenditureAccount account,
    required ExpenditureAccountPdfFilter filter,
  }) async {
    final pdfBytes = await generateExpenditureAccountPdf(
      provider: provider,
      account: account,
      filter: filter,
    );
    final filterSuffix = filter == ExpenditureAccountPdfFilter.all
        ? 'All'
        : (filter == ExpenditureAccountPdfFilter.cashOnly
            ? 'Cash'
            : (filter == ExpenditureAccountPdfFilter.upiOnly ? 'UPI' : 'Bank'));
    final safeName = '${account.accountName.replaceAll(' ', '_')}_Expense_${filterSuffix}_${provider.currentYear}.pdf';
    await Printing.sharePdf(
      bytes: pdfBytes,
      filename: safeName,
    );
  }

  /// Core Expenditure Account PDF Generator
  static Future<Uint8List> generateExpenditureAccountPdf({
    required PujaProvider provider,
    required ExpenditureAccount account,
    required ExpenditureAccountPdfFilter filter,
  }) async {
    final doc = pw.Document();

    final fontRegular = await _getFontRegular();
    final fontBold = await _getFontBold();
    final nowStr = _dateFormat.format(DateTime.now());

    final allVouchers = provider.getAccountExpenses(account.id);
    List<ExpenseVoucher> vouchers;
    String reportSubtitle;

    switch (filter) {
      case ExpenditureAccountPdfFilter.all:
        vouchers = List.from(allVouchers);
        reportSubtitle = 'COMPLETE EXPENDITURE & VOUCHERS LEDGER';
        break;
      case ExpenditureAccountPdfFilter.cashOnly:
        vouchers = allVouchers.where((v) => v.paymentMode == PaymentMode.cash).toList();
        reportSubtitle = 'PHYSICAL CASH EXPENDITURE VOUCHERS';
        break;
      case ExpenditureAccountPdfFilter.upiOnly:
        vouchers = allVouchers.where((v) => v.paymentMode == PaymentMode.upi).toList();
        reportSubtitle = 'UPI & ONLINE PAYMENT VOUCHERS';
        break;
      case ExpenditureAccountPdfFilter.bankOnly:
        vouchers = allVouchers.where((v) => v.paymentMode == PaymentMode.bankTransfer).toList();
        reportSubtitle = 'BANK TRANSFER EXPENDITURE VOUCHERS';
        break;
    }

    vouchers.sort((a, b) => b.date.compareTo(a.date));

    final totalSpent = vouchers.fold<double>(0.0, (sum, v) => sum + v.amount);
    final allTotalSpent = provider.getAccountTotalSpent(account.id);
    final budget = account.allocatedBudget;
    final remainingBudget = provider.getAccountRemainingBudget(account);

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(30),
        maxPages: 10000,
        theme: pw.ThemeData.withFont(
          base: fontRegular,
          bold: fontBold,
        ),
        header: (pw.Context context) {
          return pw.Container(
            margin: const pw.EdgeInsets.only(bottom: 12),
            padding: const pw.EdgeInsets.symmetric(horizontal: 14, vertical: 10),
            decoration: pw.BoxDecoration(
              color: PdfColors.blueGrey900,
              borderRadius: pw.BorderRadius.circular(8),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      provider.pujaName.toUpperCase(),
                      style: pw.TextStyle(
                        color: PdfColors.amber300,
                        fontSize: 15,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                    pw.SizedBox(height: 2),
                    pw.Text(
                      '${account.accountName.toUpperCase()} • $reportSubtitle',
                      style: const pw.TextStyle(
                        color: PdfColors.white,
                        fontSize: 9.5,
                      ),
                    ),
                    pw.Text(
                      'Category: ${account.category.displayName} • In-Charge: ${account.inChargeName ?? "Cashier Desk"}',
                      style: const pw.TextStyle(
                        color: PdfColors.grey400,
                        fontSize: 8,
                      ),
                    ),
                  ],
                ),
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.end,
                  children: [
                    pw.Text(
                      'DATE OF ISSUE',
                      style: const pw.TextStyle(color: PdfColors.grey400, fontSize: 7),
                    ),
                    pw.Text(
                      nowStr,
                      style: const pw.TextStyle(color: PdfColors.white, fontSize: 8),
                    ),
                    pw.SizedBox(height: 2),
                    pw.Container(
                      padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 1.5),
                      decoration: pw.BoxDecoration(
                        color: PdfColors.blueGrey800,
                        borderRadius: pw.BorderRadius.circular(4),
                      ),
                      child: pw.Text(
                        '${vouchers.length} VOUCHERS',
                        style: const pw.TextStyle(
                          color: PdfColors.amber200,
                          fontSize: 7.5,
                          fontWeight: pw.FontWeight.bold,
                        ),
                      ),
                    ),
                  ],
                ),
              ],
            ),
          );
        },
        footer: (pw.Context context) {
          return pw.Container(
            margin: const pw.EdgeInsets.only(top: 10),
            padding: const pw.EdgeInsets.only(top: 6),
            decoration: const pw.BoxDecoration(
              border: pw.Border(top: pw.BorderSide(color: PdfColors.grey300, width: 0.5)),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  '${provider.pujaName} • Expenditure Account: ${account.accountName} • Cashier: ${provider.cashierName}',
                  style: const pw.TextStyle(fontSize: 7, color: PdfColors.grey600),
                ),
                pw.Text(
                  'Page ${context.pageNumber} of ${context.pagesCount}',
                  style: const pw.TextStyle(fontSize: 7, color: PdfColors.grey600),
                ),
              ],
            ),
          );
        },
        build: (pw.Context context) {
          return [
            // KPI Summary Row
            pw.Row(
              children: [
                pw.Expanded(
                  child: _kpiBox(
                    'BUDGET ALLOCATED',
                    budget != null && budget > 0 ? _currency.format(budget) : 'Not Capped',
                    'Spending Limit',
                    PdfColors.blue50,
                    PdfColors.blue900,
                  ),
                ),
                pw.SizedBox(width: 8),
                pw.Expanded(
                  child: _kpiBox(
                    filter == ExpenditureAccountPdfFilter.all ? 'TOTAL SPENT' : 'FILTER SPENT',
                    _currency.format(totalSpent),
                    '${vouchers.length} Vouchers Recorded',
                    PdfColors.red50,
                    PdfColors.red900,
                  ),
                ),
                pw.SizedBox(width: 8),
                pw.Expanded(
                  child: _kpiBox(
                    'REMAINING BUDGET',
                    budget != null && budget > 0 ? _currency.format(remainingBudget) : '--',
                    budget != null && budget > 0
                        ? (remainingBudget >= 0 ? 'Within Allocation' : 'Over Budget!')
                        : 'No limit set',
                    remainingBudget < 0 ? PdfColors.red50 : PdfColors.green50,
                    remainingBudget < 0 ? PdfColors.red900 : PdfColors.green900,
                  ),
                ),
                pw.SizedBox(width: 8),
                pw.Expanded(
                  child: _kpiBox(
                    'TOTAL ACCOUNT SPENT',
                    _currency.format(allTotalSpent),
                    budget != null && budget > 0
                        ? '${((allTotalSpent / budget) * 100).toStringAsFixed(1)}% Budget Consumed'
                        : 'Total Account Expenses',
                    PdfColors.amber50,
                    PdfColors.amber900,
                  ),
                ),
              ],
            ),
            pw.SizedBox(height: 14),

            // Vouchers Table
            if (vouchers.isEmpty)
              pw.Container(
                padding: const pw.EdgeInsets.all(24),
                alignment: pw.Alignment.center,
                decoration: pw.BoxDecoration(
                  color: PdfColors.grey100,
                  borderRadius: pw.BorderRadius.circular(6),
                ),
                child: pw.Text(
                  'No expense vouchers found matching this filter.',
                  style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey700),
                ),
              )
            else ...[
              pw.Text(
                'OFFICIAL EXPENSE VOUCHERS REGISTER',
                style: pw.TextStyle(fontSize: 9.5, fontWeight: pw.FontWeight.bold, color: PdfColors.blueGrey800),
              ),
              pw.SizedBox(height: 5),
              pw.TableHelper.fromTextArray(
                headers: ['Voucher #', 'Date', 'Payee / Vendor', 'Description / Note', 'Paid By', 'Mode', 'Amount (Rs.)'],
                data: vouchers.map((v) {
                  return [
                    '#${v.voucherNo}',
                    DateFormat('dd/MM/yyyy').format(v.date),
                    v.payeeName,
                    v.description != null && v.description!.isNotEmpty ? v.description! : '--',
                    v.paidBy.isNotEmpty ? v.paidBy : 'Cashier',
                    v.paymentMode.name.toUpperCase(),
                    _currency.format(v.amount),
                  ];
                }).toList(),
                headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 7.5, color: PdfColors.white),
                headerDecoration: const pw.BoxDecoration(color: PdfColors.blueGrey800),
                cellStyle: const pw.TextStyle(fontSize: 7),
                cellAlignment: pw.Alignment.centerLeft,
                cellPadding: const pw.EdgeInsets.symmetric(horizontal: 4, vertical: 3.5),
              ),
              pw.Container(
                padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 4),
                color: PdfColors.grey200,
                child: pw.Row(
                  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                  children: [
                    pw.Text('Total Vouchers: ${vouchers.length}', style: pw.TextStyle(fontSize: 8, fontWeight: pw.FontWeight.bold)),
                    pw.Text('Total Expenditure: ${_currency.format(totalSpent)}', style: pw.TextStyle(fontSize: 8.5, fontWeight: pw.FontWeight.bold, color: PdfColors.red900)),
                  ],
                ),
              ),
            ],
            pw.SizedBox(height: 24),

            // Signatories Section
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Column(
                  children: [
                    pw.Container(width: 120, height: 0.8, color: PdfColors.grey600),
                    pw.SizedBox(height: 4),
                    pw.Text('Account In-Charge', style: pw.TextStyle(fontSize: 8.5, fontWeight: pw.FontWeight.bold)),
                    pw.Text(account.inChargeName ?? 'Authorized In-Charge', style: const pw.TextStyle(fontSize: 7.5, color: PdfColors.grey700)),
                  ],
