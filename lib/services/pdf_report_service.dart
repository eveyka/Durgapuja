  /// Generate & Launch Collection Account PDF Print / Save Preview
  static Future<void> printCollectionAccountReport({
    required PujaProvider provider,
    required CollectionAccount account,
    required CollectionAccountPdfFilter filter,
  }) async {
    final pdfBytes = await generateCollectionAccountPdf(
