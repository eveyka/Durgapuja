  static List<pw.Widget> _buildAllTransactionsTable(
    List<ChandaSlip> slips,
    List<ExpenseVoucher> expenses,
    List<MemberAdvance> advances,
    double totalCollected,
    double totalExpense,
    double netBalance,
  ) {
    final List<_PdfUnifiedRow> rows = [];

    for (final s in slips) {
      rows.add(_PdfUnifiedRow(
        date: s.createdAt,
        type: 'DONATION',
        particulars: s.donorName + (s.phone != null && s.phone!.isNotEmpty ? ' (${s.phone})' : ''),
        ref: 'Book #${s.bookNumber} • SL #${s.slipNumber}',
        mode: s.paymentMode.name.toUpperCase(),
        inflow: s.amount,
        outflow: 0.0,
      ));
    }

    for (final e in expenses) {
      rows.add(_PdfUnifiedRow(
        date: e.date,
        type: 'EXPENSE',
        particulars: e.payeeName + (e.description != null && e.description!.isNotEmpty ? ' - ${e.description}' : ''),
        ref: 'Voucher #${e.voucherNo} • ${e.category.displayName}',
        mode: e.paymentMode.name.toUpperCase(),
        inflow: 0.0,
        outflow: e.amount,
      ));
    }

    for (final a in advances) {
      rows.add(_PdfUnifiedRow(
        date: a.dateGiven,
        type: 'ADVANCE',
        particulars: '${a.memberName} (${a.purpose})',
        ref: 'Category: ${a.category.displayName} [${a.status.toUpperCase()}]',
        mode: a.paymentMode.name.toUpperCase(),
        inflow: 0.0,
        outflow: a.advanceAmount,
      ));
    }

    // Chronological order for statement
    rows.sort((a, b) => a.date.compareTo(b.date));

    if (rows.isEmpty) {
      return [
        pw.Container(
          padding: const pw.EdgeInsets.all(20),
          alignment: pw.Alignment.center,
          child: pw.Text('No transactions recorded for this event.', style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey600)),
        ),
      ];
    }

    return [
      pw.Text('COMPLETE EVENT TRANSACTIONS LEDGER (CHRONOLOGICAL)', style: pw.TextStyle(fontSize: 9.5, fontWeight: pw.FontWeight.bold, color: PdfColors.blueGrey800)),
      pw.SizedBox(height: 5),
      pw.TableHelper.fromTextArray(
        headers: ['Date', 'Type', 'Particulars & Payee', 'Reference / Category', 'Mode', 'Inflow (Rs.)', 'Outflow (Rs.)'],
        data: rows.map((r) {
          return [
            DateFormat('dd/MM/yy').format(r.date),
            r.type,
            r.particulars,
            r.ref,
            r.mode,
            r.inflow > 0 ? _currency.format(r.inflow) : '-',
            r.outflow > 0 ? _currency.format(r.outflow) : '-',
          ];
        }).toList(),
        headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 7.5, color: PdfColors.white),
        headerDecoration: const pw.BoxDecoration(color: PdfColors.blueGrey800),
        cellStyle: const pw.TextStyle(fontSize: 7),
        cellAlignment: pw.Alignment.centerLeft,
        cellPadding: const pw.EdgeInsets.symmetric(horizontal: 4, vertical: 3),
      ),
      pw.Container(
        padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 4),
        color: PdfColors.grey200,
        child: pw.Row(
          mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
          children: [
            pw.Text('Grand Inflow: ${_currency.format(totalCollected)}', style: pw.TextStyle(fontSize: 8, fontWeight: pw.FontWeight.bold, color: PdfColors.green900)),
            pw.Text('Grand Outflow: ${_currency.format(totalExpense)}', style: pw.TextStyle(fontSize: 8, fontWeight: pw.FontWeight.bold, color: PdfColors.red900)),
            pw.Text('Net Surplus: ${_currency.format(netBalance)}', style: pw.TextStyle(fontSize: 8.5, fontWeight: pw.FontWeight.bold, color: netBalance >= 0 ? PdfColors.blue900 : PdfColors.red900)),
          ],
        ),
      ),
    ];
  }

  static List<pw.Widget> _buildCollectionsOnlyTable(List<ChandaSlip> slips, double totalCollected) {
    if (slips.isEmpty) {
      return [
        pw.Container(
          padding: const pw.EdgeInsets.all(20),
          alignment: pw.Alignment.center,
          child: pw.Text('No donation slips recorded for this event.', style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey600)),
        ),
      ];
    }

    final sortedSlips = List<ChandaSlip>.from(slips)
      ..sort((a, b) {
        final cmp = a.bookNumber.compareTo(b.bookNumber);
        if (cmp != 0) return cmp;
        return a.slipNumber.compareTo(b.slipNumber);
      });

    return [
      pw.Text('DONATION & CHANDA COLLECTION SLIPS REGISTER', style: pw.TextStyle(fontSize: 9.5, fontWeight: pw.FontWeight.bold, color: PdfColors.blueGrey800)),
      pw.SizedBox(height: 5),
      pw.TableHelper.fromTextArray(
        headers: ['Book #', 'SL No.', 'Date', 'Donor Name & Details', 'Collector', 'Mode', 'Amount (INR)', 'Status'],
        data: sortedSlips.map((s) {
          final phoneStr = s.phone != null && s.phone!.isNotEmpty ? ' • ${s.phone}' : '';
          final samagri = s.isInKind ? ' [Samagri: ${s.inKindItemName ?? ""}]' : '';
          final installmentSummary = s.payments.length > 1
              ? '\n(${s.payments.length} Payments: ${s.payments.map((p) => '${DateFormat("dd/MM").format(p.date)}: Rs.${p.amount.toInt()}').join(', ')})'
              : '';
          final amtDisplay = s.pendingAmount > 0
              ? '${_currency.format(s.paidAmount)} (Due: ${_currency.format(s.pendingAmount)})'
              : _currency.format(s.paidAmount);
          return [
            '#${s.bookNumber}',
            '#${s.slipNumber}',
            DateFormat('dd/MM/yyyy').format(s.paymentDate ?? s.createdAt),
            '${s.donorName}$phoneStr$samagri$installmentSummary',
            s.collectedBy.isNotEmpty ? s.collectedBy : 'Cashier',
            s.paymentMode.name.toUpperCase(),
            amtDisplay,
            s.isFullyPaid ? 'PAID' : (s.isPartial ? 'PARTIAL' : 'DUE'),
          ];
        }).toList(),
        headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, fontSize: 7.5, color: PdfColors.white),
        headerDecoration: const pw.BoxDecoration(color: PdfColors.blueGrey800),
        cellStyle: const pw.TextStyle(fontSize: 7),
        cellAlignments: {
          0: pw.Alignment.center,
          1: pw.Alignment.center,
          2: pw.Alignment.center,
          3: pw.Alignment.centerLeft,
          4: pw.Alignment.centerLeft,
          5: pw.Alignment.center,
          6: pw.Alignment.centerRight,
          7: pw.Alignment.center,
        },
        cellPadding: const pw.EdgeInsets.symmetric(horizontal: 4, vertical: 3),
      ),
      pw.Container(
        padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 4),
