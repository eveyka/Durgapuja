              totalExpense: totalExpense,
              netBalance: netBalance,
              totalAdvances: totalAdvances,
              pendingAdvances: pendingAdvances,
              slipsCount: slips.length,
              expensesCount: expenses.length,
              advancesCount: advances.length,
              totalReturned: totalReturned,
            ),
            pw.SizedBox(height: 14),

            // Specific Content based on reportType
            if (reportType == EventPdfReportType.allTransactions)
              ..._buildAllTransactionsTable(slips, expenses, advances, totalCollected, totalExpense, netBalance)
            else if (reportType == EventPdfReportType.collectionsOnly)
              ..._buildCollectionsOnlyTable(slips, totalCollected)
            else if (reportType == EventPdfReportType.expensesOnly)
              ..._buildExpensesOnlyTable(expenses, totalExpense)
            else if (reportType == EventPdfReportType.advancesOnly)
              ..._buildAdvancesOnlyTable(advances, totalAdvances, totalActualSpent, totalReturned, pendingAdvances),

            pw.SizedBox(height: 20),

            // Official Signatories Block
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Column(
                  children: [
                    pw.Container(width: 100, height: 1, color: PdfColors.grey600),
                    pw.SizedBox(height: 4),
                    pw.Text('President', style: pw.TextStyle(fontSize: 8, fontWeight: pw.FontWeight.bold)),
                    pw.Text(provider.presidentName, style: const pw.TextStyle(fontSize: 7, color: PdfColors.grey700)),
                  ],
                ),
                pw.Column(
                  children: [
                    pw.Container(width: 100, height: 1, color: PdfColors.grey600),
                    pw.SizedBox(height: 4),
                    pw.Text('General Secretary', style: pw.TextStyle(fontSize: 8, fontWeight: pw.FontWeight.bold)),
                    pw.Text(provider.secretaryName, style: const pw.TextStyle(fontSize: 7, color: PdfColors.grey700)),
                  ],
                ),
                pw.Column(
                  children: [
                    pw.Container(width: 100, height: 1, color: PdfColors.grey600),
                    pw.SizedBox(height: 4),
                    pw.Text('Cashier / Treasurer', style: pw.TextStyle(fontSize: 8, fontWeight: pw.FontWeight.bold)),
                    pw.Text(provider.cashierName, style: const pw.TextStyle(fontSize: 7, color: PdfColors.grey700)),
                  ],
                ),
              ],
            ),
          ];
        },
      ),
    );

    return doc.save();
  }

  static pw.Widget _buildEventKpiSummary({
    required EventPdfReportType reportType,
    required double totalCollected,
    required double totalExpense,
    required double netBalance,
    required double totalAdvances,
    required double pendingAdvances,
    required int slipsCount,
    required int expensesCount,
    required int advancesCount,
    required double totalReturned,
  }) {
    if (reportType == EventPdfReportType.allTransactions) {
      return pw.Row(
        children: [
          pw.Expanded(child: _kpiBox('TOTAL INFLOW', _currency.format(totalCollected), '$slipsCount Donations', PdfColors.green50, PdfColors.green800)),
          pw.SizedBox(width: 8),
          pw.Expanded(child: _kpiBox('TOTAL OUTFLOW', _currency.format(totalExpense), '$expensesCount Vouchers', PdfColors.red50, PdfColors.red800)),
          pw.SizedBox(width: 8),
          pw.Expanded(child: _kpiBox('PENDING ADVANCES', _currency.format(pendingAdvances), '$advancesCount Members', PdfColors.amber50, PdfColors.amber800)),
          pw.SizedBox(width: 8),
          pw.Expanded(child: _kpiBox('NET BALANCE', _currency.format(netBalance), netBalance >= 0 ? 'Surplus' : 'Deficit', PdfColors.blue50, PdfColors.blue900)),
        ],
      );
    } else if (reportType == EventPdfReportType.collectionsOnly) {
      return pw.Row(
        children: [
          pw.Expanded(child: _kpiBox('TOTAL CHANDA', _currency.format(totalCollected), 'Total Collected', PdfColors.green50, PdfColors.green800)),
          pw.SizedBox(width: 8),
          pw.Expanded(child: _kpiBox('TOTAL SLIPS', '$slipsCount', 'Donation Slips', PdfColors.blue50, PdfColors.blue800)),
          pw.SizedBox(width: 8),
          pw.Expanded(child: _kpiBox('AVG DONATION', slipsCount > 0 ? _currency.format(totalCollected / slipsCount) : 'Rs. 0.00', 'Per Donor', PdfColors.amber50, PdfColors.amber800)),
        ],
      );
    } else if (reportType == EventPdfReportType.expensesOnly) {
      return pw.Row(
        children: [
          pw.Expanded(child: _kpiBox('TOTAL EXPENSES', _currency.format(totalExpense), 'Total Outflow', PdfColors.red50, PdfColors.red800)),
          pw.SizedBox(width: 8),
          pw.Expanded(child: _kpiBox('VOUCHERS', '$expensesCount', 'Expense Slips', PdfColors.blue50, PdfColors.blue800)),
          pw.SizedBox(width: 8),
          pw.Expanded(child: _kpiBox('AVG VOUCHER', expensesCount > 0 ? _currency.format(totalExpense / expensesCount) : 'Rs. 0.00', 'Per Voucher', PdfColors.amber50, PdfColors.amber800)),
        ],
      );
    } else {
      // advancesOnly
      return pw.Row(
        children: [
          pw.Expanded(child: _kpiBox('ADVANCES GIVEN', _currency.format(totalAdvances), '$advancesCount Disbursed', PdfColors.amber50, PdfColors.amber800)),
