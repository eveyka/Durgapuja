class PdfReportService {
  static final _currency = NumberFormat.currency(locale: 'en_IN', symbol: 'Rs. ', decimalDigits: 2);
  static final _dateFormat = DateFormat('dd MMM yyyy, hh:mm a');

  static Future<pw.Font> _getFontRegular() async {
    try {
      return await PdfGoogleFonts.interRegular();
    } catch (_) {
      return pw.Font.helvetica();
    }
  }

  static Future<pw.Font> _getFontBold() async {
    try {
      return await PdfGoogleFonts.interBold();
    } catch (_) {
      return pw.Font.helveticaBold();
    }
  }

  /// Generate & Launch PDF Print / Save Preview
  static Future<void> printAuditReport(PujaProvider provider) async {
    final pdfBytes = await generateAuditReportPdf(provider);
    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdfBytes,
      name: '${provider.pujaName.replaceAll(' ', '_')}_Audit_Report_${provider.currentYear}.pdf',
    );
  }

  /// Generate & Share PDF directly via WhatsApp / Apps
  static Future<void> shareAuditReport(PujaProvider provider) async {
    final pdfBytes = await generateAuditReportPdf(provider);
    await Printing.sharePdf(
      bytes: pdfBytes,
      filename: '${provider.pujaName.replaceAll(' ', '_')}_Financial_Statement_${provider.currentYear}.pdf',
    );
  }

