          pw.SizedBox(width: 8),
          pw.Expanded(child: _kpiBox('PENDING TO SETTLE', _currency.format(pendingAdvances), 'Active Advances', PdfColors.red50, PdfColors.red800)),
        ],
      );
    }
  }

