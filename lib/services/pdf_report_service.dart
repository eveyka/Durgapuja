  /// Core All Events Combined Unified Transactions Ledger
  static Future<Uint8List> generateAllEventsLedgerPdf(PujaProvider provider) async {
    final doc = pw.Document();

    final fontRegular = await _getFontRegular();
    final fontBold = await _getFontBold();

    final nowStr = _dateFormat.format(DateTime.now());

    // Build event name mapping
    final eventMap = <String, String>{};
    for (final ev in provider.events) {
      eventMap[ev.id] = ev.name;
    }
    final defaultEventName = provider.events.isNotEmpty ? provider.events.first.name : 'General';

    final List<_PdfUnifiedRow> rows = [];

    // All slips
    for (final s in provider.slips) {
      final evName = s.eventId != null ? (eventMap[s.eventId] ?? defaultEventName) : defaultEventName;
      rows.add(_PdfUnifiedRow(
        date: s.createdAt,
        type: 'DONATION',
        particulars: s.donorName + (s.phone != null && s.phone!.isNotEmpty ? ' (${s.phone})' : ''),
        ref: 'Book #${s.bookNumber} • SL #${s.slipNumber}',
        mode: s.paymentMode.name.toUpperCase(),
        inflow: s.amount,
        outflow: 0.0,
        eventName: evName,
      ));
    }

    // All expenses
    for (final e in provider.expenses) {
      final evName = e.eventId != null ? (eventMap[e.eventId] ?? defaultEventName) : defaultEventName;
      rows.add(_PdfUnifiedRow(
        date: e.date,
        type: 'EXPENSE',
        particulars: e.payeeName + (e.description != null && e.description!.isNotEmpty ? ' - ${e.description}' : ''),
        ref: 'Voucher #${e.voucherNo} • ${e.category.displayName}',
        mode: e.paymentMode.name.toUpperCase(),
        inflow: 0.0,
        outflow: e.amount,
        eventName: evName,
      ));
    }

    // All advances
    for (final a in provider.advances) {
      final evName = a.eventId != null ? (eventMap[a.eventId] ?? defaultEventName) : defaultEventName;
      rows.add(_PdfUnifiedRow(
        date: a.dateGiven,
        type: 'ADVANCE',
        particulars: '${a.memberName} (${a.purpose})',
        ref: 'Category: ${a.category.displayName} [${a.status.toUpperCase()}]',
        mode: a.paymentMode.name.toUpperCase(),
        inflow: 0.0,
        outflow: a.advanceAmount,
        eventName: evName,
      ));
    }

    rows.sort((a, b) => a.date.compareTo(b.date));

    final grandInflow = provider.totalIncome;
    final grandOutflow = provider.totalExpense;
    final netBalance = provider.netBalance;
    final pendingAdvances = provider.totalPendingAdvance;

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(30),
        maxPages: 10000,
        theme: pw.ThemeData.withFont(
          base: fontRegular,
          bold: fontBold,
        ),
        header: (pw.Context context) {
          return pw.Container(
            margin: const pw.EdgeInsets.only(bottom: 12),
            padding: const pw.EdgeInsets.symmetric(horizontal: 14, vertical: 10),
            decoration: pw.BoxDecoration(
              color: PdfColors.blueGrey900,
              borderRadius: pw.BorderRadius.circular(8),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      provider.pujaName.toUpperCase(),
                      style: pw.TextStyle(
                        color: PdfColors.amber300,
                        fontSize: 15,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                    pw.SizedBox(height: 2),
                    pw.Text(
                      'ALL FESTIVALS CONSOLIDATED TRANSACTIONS REGISTER & AUDIT LEDGER',
                      style: const pw.TextStyle(
                        color: PdfColors.white,
                        fontSize: 8.5,
                      ),
                    ),
                    pw.Text(
                      'Comprehensive Committee Ledger • Cashier Desk: ${provider.cashierName}',
                      style: const pw.TextStyle(
                        color: PdfColors.grey400,
                        fontSize: 7.5,
                      ),
                    ),
                  ],
                ),
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.end,
                  children: [
                    pw.Text(
                      'DATE OF ISSUE',
                      style: const pw.TextStyle(color: PdfColors.grey400, fontSize: 7),
                    ),
                    pw.Text(
                      nowStr,
                      style: const pw.TextStyle(color: PdfColors.white, fontSize: 8),
                    ),
                    pw.SizedBox(height: 2),
                    pw.Container(
                      padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 1.5),
                      decoration: pw.BoxDecoration(
                        color: PdfColors.blueGrey800,
                        borderRadius: pw.BorderRadius.circular(4),
                      ),
                      child: pw.Text(
                        '${provider.events.length} EVENTS COMBINED',
                        style: const pw.TextStyle(
                          color: PdfColors.amber200,
                          fontSize: 7.5,
                          fontWeight: pw.FontWeight.bold,
                        ),
                      ),
                    ),
                  ],
                ),
              ],
            ),
          );
        },
        footer: (pw.Context context) {
          return pw.Container(
            margin: const pw.EdgeInsets.only(top: 10),
            padding: const pw.EdgeInsets.only(top: 6),
            decoration: const pw.BoxDecoration(
              border: pw.Border(top: pw.BorderSide(color: PdfColors.grey300, width: 0.5)),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  '${provider.pujaName} • Consolidated Audit Register',
                  style: const pw.TextStyle(fontSize: 7, color: PdfColors.grey600),
                ),
                pw.Text(
                  'Page ${context.pageNumber} of ${context.pagesCount}',
                  style: const pw.TextStyle(fontSize: 7, color: PdfColors.grey600),
                ),
              ],
            ),
          );
        },
        build: (pw.Context context) {
          return [
            // KPI Summary Row
            pw.Row(
              children: [
                pw.Expanded(child: _kpiBox('TOTAL INFLOW', _currency.format(grandInflow), '${provider.slips.length} Donations', PdfColors.green50, PdfColors.green800)),
                pw.SizedBox(width: 8),
                pw.Expanded(child: _kpiBox('TOTAL OUTFLOW', _currency.format(grandOutflow), '${provider.expenses.length} Vouchers', PdfColors.red50, PdfColors.red800)),
                pw.SizedBox(width: 8),
