  /// Generate & Launch Event PDF Print / Save Preview
  static Future<void> printEventReport({
    required PujaProvider provider,
    required PujaEvent event,
    required EventPdfReportType reportType,
  }) async {
    final pdfBytes = await generateEventReportPdf(
      provider: provider,
      event: event,
      reportType: reportType,
    );
    final safeName = '${event.name.replaceAll(' ', '_')}_${reportType.name}_${event.year}.pdf';
    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdfBytes,
      name: safeName,
    );
  }

  /// Generate & Share Event PDF directly via WhatsApp / Apps
  static Future<void> shareEventReport({
    required PujaProvider provider,
    required PujaEvent event,
    required EventPdfReportType reportType,
  }) async {
    final pdfBytes = await generateEventReportPdf(
      provider: provider,
      event: event,
      reportType: reportType,
    );
    final safeName = '${event.name.replaceAll(' ', '_')}_${reportType.name}_${event.year}.pdf';
    await Printing.sharePdf(
      bytes: pdfBytes,
      filename: safeName,
    );
  }

  /// Core Event PDF Generator by Report Type
  static Future<Uint8List> generateEventReportPdf({
    required PujaProvider provider,
    required PujaEvent event,
    required EventPdfReportType reportType,
  }) async {
    final doc = pw.Document();

    final fontRegular = await _getFontRegular();
    final fontBold = await _getFontBold();

    final nowStr = _dateFormat.format(DateTime.now());

    // Filter event-specific data
    final slips = provider.slips.where((s) => s.eventId == event.id).toList()
      ..sort((a, b) => b.createdAt.compareTo(a.createdAt));
    final expenses = provider.expenses.where((e) => e.eventId == event.id).toList()
      ..sort((a, b) => b.date.compareTo(a.date));
    final advances = provider.advances.where((a) => a.eventId == event.id).toList()
      ..sort((a, b) => b.dateGiven.compareTo(a.dateGiven));

    final totalCollected = slips.fold<double>(0.0, (sum, s) => sum + s.amount);
    final totalExpense = expenses.fold<double>(0.0, (sum, e) => sum + e.amount);
    final totalAdvances = advances.fold<double>(0.0, (sum, a) => sum + a.advanceAmount);
    final pendingAdvances = advances
        .where((a) => a.status == 'Pending')
        .fold<double>(0.0, (sum, a) => sum + a.advanceAmount);
    final totalActualSpent = advances.fold<double>(0.0, (sum, a) => sum + (a.actualSpent ?? 0.0));
    final totalReturned = advances.fold<double>(0.0, (sum, a) => sum + (a.returnAmount ?? 0.0));
    final netBalance = totalCollected - totalExpense;

    String reportTitle;
    switch (reportType) {
      case EventPdfReportType.allTransactions:
        reportTitle = 'EVENT FINANCIAL STATEMENT & COMPLETE TRANSACTIONS LEDGER';
        break;
      case EventPdfReportType.collectionsOnly:
        reportTitle = 'CHANDA & DONATIONS COLLECTION REGISTER';
        break;
      case EventPdfReportType.expensesOnly:
        reportTitle = 'OFFICIAL EXPENDITURE & VOUCHERS REGISTER';
        break;
      case EventPdfReportType.advancesOnly:
        reportTitle = 'MEMBER CASH ADVANCES & SETTLEMENT REGISTER';
        break;
    }

    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(30),
        maxPages: 10000,
        theme: pw.ThemeData.withFont(
          base: fontRegular,
          bold: fontBold,
        ),
        header: (pw.Context context) {
          return pw.Container(
            margin: const pw.EdgeInsets.only(bottom: 12),
            padding: const pw.EdgeInsets.symmetric(horizontal: 14, vertical: 10),
            decoration: pw.BoxDecoration(
              color: PdfColors.blueGrey900,
              borderRadius: pw.BorderRadius.circular(8),
            ),
            child: pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                      '${event.name.toUpperCase()} (${event.year})',
                      style: pw.TextStyle(
                        color: PdfColors.amber300,
                        fontSize: 15,
                        fontWeight: pw.FontWeight.bold,
                      ),
                    ),
                    pw.SizedBox(height: 2),
                    pw.Text(
                      reportTitle,
                      style: const pw.TextStyle(
                        color: PdfColors.white,
                        fontSize: 9.5,
                      ),
                    ),
                    pw.Text(
                      '${provider.pujaName} • Cashier Desk: ${provider.cashierName}',
                      style: const pw.TextStyle(
                        color: PdfColors.grey400,
                        fontSize: 8,
                      ),
                    ),
                  ],
                ),
                pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.end,
                  children: [
                    pw.Text(
                      'DATE OF ISSUE',
                      style: const pw.TextStyle(color: PdfColors.grey400, fontSize: 7),
                    ),
                    pw.Text(
                      nowStr,
                      style: const pw.TextStyle(color: PdfColors.white, fontSize: 8),
                    ),
                    pw.SizedBox(height: 2),
                    pw.Container(
                      padding: const pw.EdgeInsets.symmetric(horizontal: 6, vertical: 1.5),
                      decoration: pw.BoxDecoration(
                        color: PdfColors.blueGrey800,
                        borderRadius: pw.BorderRadius.circular(4),
                      ),
                      child: pw.Text(
                        event.status.toUpperCase(),
                        style: const pw.TextStyle(
                          color: PdfColors.amber200,
                          fontSize: 7.5,
                          fontWeight: pw.FontWeight.bold,
                        ),
                      ),
                    ),
                  ],
                ),
              ],
            ),
          );
