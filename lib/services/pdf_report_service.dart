  /// Core Collection Account PDF Generator — Professional Structured Format
  static Future<Uint8List> generateCollectionAccountPdf({
    required PujaProvider provider,
    required CollectionAccount account,
    required CollectionAccountPdfFilter filter,
  }) async {
    final doc = pw.Document();

    final fontRegular = await _getFontRegular();
    final fontBold = await _getFontBold();
    final nowStr = _dateFormat.format(DateTime.now());
    final shortDate = DateFormat('dd MMM yyyy').format(DateTime.now());

    final allSlips = provider.getAccountSlips(account.id);
    List<ChandaSlip> slips;
    String filterLabel;

    switch (filter) {
      case CollectionAccountPdfFilter.all:
        slips = List.from(allSlips);
        filterLabel = 'ALL CONTRIBUTORS';
        break;
      case CollectionAccountPdfFilter.onlyUnpaid:
        slips = allSlips.where((s) => s.isUnpaid || s.pendingAmount > 0).toList();
        filterLabel = 'OUTSTANDING / UNPAID ONLY';
        break;
      case CollectionAccountPdfFilter.onlyPaid:
        slips = allSlips.where((s) => s.paidAmount > 0).toList();
        filterLabel = 'COLLECTED & PAID CONTRIBUTIONS';
        break;
    }

    slips.sort((a, b) {
      final cmp = a.bookNumber.compareTo(b.bookNumber);
      if (cmp != 0) return cmp;
      return a.slipNumber.compareTo(b.slipNumber);
    });

    final unpaidSlips = slips.where((s) => s.isUnpaid || s.pendingAmount > 0).toList();
    final paidSlips = slips.where((s) => s.paidAmount > 0).toList();

    final totalPledged = slips.fold<double>(0.0, (sum, s) => sum + s.amount);
    final totalPaid = slips.fold<double>(0.0, (sum, s) => sum + s.paidAmount);
    final totalDue = slips.fold<double>(0.0, (sum, s) => sum + s.pendingAmount);

    final allPayments = <Map<String, dynamic>>[];
    for (final s in slips) {
      for (final p in s.payments) {
        allPayments.add({'payment': p, 'slip': s});
      }
    }
    allPayments.sort((a, b) => (a['payment'] as SlipPayment).date.compareTo((b['payment'] as SlipPayment).date));

    final bookRange = account.bookNumber != null
        ? 'Book #${account.bookNumber}  (SL: ${account.startSlip ?? 1} – ${account.endSlip ?? '?'})'
        : 'Open Book Account';


    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.symmetric(horizontal: 28, vertical: 20),
        maxPages: 10000,
        theme: pw.ThemeData.withFont(base: fontRegular, bold: fontBold),
